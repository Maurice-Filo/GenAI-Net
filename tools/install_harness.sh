#!/usr/bin/env bash
# User-local installation of the Harness release supported by GenAI-Net.
set -euo pipefail
umask 077

HARNESS_VERSION=0.1.0-rc.8
NODE_VERSION=v24.19.0
PNPM_VERSION=11.7.0
prefix="$HOME/.local/share/genainet"
config_dir="$HOME/.config/genainet-dsh"
runtime_dir=""
port=3080
open_browser=1
serve=1
ask_key=1
scratch=""
usage() {
    cat <<'EOF'
Usage: bash tools/install_harness.sh [options]

Downloads the pinned DeepSeek Harness, initializes its configuration and starts
its local GUI. Press Enter at the optional API-key prompt to configure it in the
GUI instead. Existing configuration and credentials are preserved.

  --prefix PATH       Installation prefix (default: ~/.local/share/genainet)
  --config-dir PATH   Harness home (default: ~/.config/genainet-dsh)
  --runtime-dir PATH  Use/install the pinned runtime in this directory
  --port PORT         GUI port (default: 3080)
  --no-open           Do not open a browser
  --no-gui            Install/configure only
  --skip-api-key      Skip the optional key prompt
  -h, --help          Show this help

Requires Linux, Bash, Python 3, curl, tar, xz and sha256sum. Node 24 is reused
when available; otherwise a verified official binary is downloaded locally.
Bubblewrap is needed for sandboxed agent tools. No sudo or LLM calls are made
by the installer; sending messages in the GUI can incur provider charges.
EOF
}
die() { printf 'Error: %s\n' "$*" >&2; exit 1; }
while (($#)); do
    case "$1" in
        --prefix|--config-dir|--runtime-dir|--port)
            (($# >= 2)) && [[ -n "$2" && "$2" != --* ]] || die "Missing value for $1"
            case "$1" in
                --prefix) prefix="$2" ;;
                --config-dir) config_dir="$2" ;;
                --runtime-dir) runtime_dir="$2" ;;
                --port) port="$2" ;;
            esac
            shift 2 ;;
        --no-open) open_browser=0; shift ;;
        --no-gui) serve=0; shift ;;
        --skip-api-key) ask_key=0; shift ;;
        -h|--help) usage; exit 0 ;;
        *) die "Unknown option: $1 (see --help)" ;;
    esac
done
[[ $(uname -s) == Linux ]] || die 'This installer supports Linux only.'
[[ "$port" =~ ^[0-9]{1,5}$ ]] || die 'Port must be an integer from 1 to 65535.'
port=$((10#$port))
((port >= 1 && port <= 65535)) || die 'Port must be between 1 and 65535.'
for tool in python3 curl tar xz sha256sum; do
    command -v "$tool" >/dev/null || die "Install required command: $tool"
done
absolute_path() { python3 -c 'import os,sys; print(os.path.abspath(os.path.expanduser(sys.argv[1])))' "$1"; }
prefix=$(absolute_path "$prefix")
config_dir=$(absolute_path "$config_dir")
runtime_dir=$(absolute_path "${runtime_dir:-$prefix/dsh-runtime}")
repo_dir=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." >/dev/null && pwd)
mkdir -p "$prefix/bin" "$config_dir"
chmod 700 "$config_dir"
cleanup() { if [[ -n "$scratch" ]]; then rm -rf -- "$scratch"; fi; }
trap cleanup EXIT
trap 'exit 130' INT
trap 'exit 143' TERM

# Preserve user-written files at the locations reserved for generated launchers.
for managed in "$prefix/env.sh" "$prefix/bin/harness-gui"; do
    if [[ -e "$managed" ]] && ! grep -q '^# Generated by GenAI-Net install_harness.sh$' "$managed"; then
        die "Refusing to replace $managed; choose another --prefix."
    fi
done
node_bin=""
if command -v node >/dev/null && [[ $(node -p 'process.versions.node.split(".")[0]') == 24 ]]; then
    node_bin=$(command -v node)
else
    case $(uname -m) in
        x86_64) arch=x64 ;;
        aarch64|arm64) arch=arm64 ;;
        *) die 'No bundled Node installation for this architecture; put Node 24 on PATH.' ;;
    esac
    node_dir="$prefix/node-${NODE_VERSION}-linux-${arch}"
    node_bin="$node_dir/bin/node"
    if [[ ! -x "$node_bin" ]]; then
        scratch=$(mktemp -d)
        archive="node-${NODE_VERSION}-linux-${arch}.tar.xz"
        printf 'Downloading Node %s (%s)…\n' "$NODE_VERSION" "$arch"
        curl --fail --location --retry 3 "https://nodejs.org/dist/$NODE_VERSION/$archive" -o "$scratch/$archive"
        curl --fail --location --retry 3 "https://nodejs.org/dist/$NODE_VERSION/SHASUMS256.txt" -o "$scratch/SHASUMS256.txt"
        expected=$(awk -v name="$archive" '$2 == name {print $1}' "$scratch/SHASUMS256.txt")
        [[ "$expected" =~ ^[a-fA-F0-9]{64}$ ]] || die 'Node checksum was not found.'
        printf '%s  %s\n' "$expected" "$scratch/$archive" | sha256sum --check --status || die 'Node checksum mismatch.'
        mkdir "$scratch/node"
        tar -xJf "$scratch/$archive" --strip-components=1 -C "$scratch/node"
        [[ ! -e "$node_dir" ]] || die "Incomplete Node directory exists: $node_dir; choose another --prefix."
        mv -- "$scratch/node" "$node_dir"
    fi
fi
node_bin=$(absolute_path "$node_bin")
export PATH="$(dirname "$node_bin"):$prefix/node-tools/node_modules/.bin:$PATH"
[[ $("$node_bin" -p 'process.versions.node.split(".")[0]') == 24 ]] || die 'Node 24 is required.'
cli="$runtime_dir/node_modules/@deepseek-ai/dsh/lib/bin.js"
package="$runtime_dir/node_modules/@deepseek-ai/dsh/package.json"
managed_pending=0
if [[ -f "$runtime_dir/.genainet-install-pending" ]]; then managed_pending=1; fi
if [[ ! -f "$package" ]] || ((managed_pending)); then
    pnpm_bin="$prefix/node-tools/node_modules/.bin/pnpm"
    if [[ ! -x "$pnpm_bin" ]] || [[ $("$pnpm_bin" --version) != "$PNPM_VERSION" ]]; then
        command -v npm >/dev/null || die 'The selected Node installation needs npm.'
        npm install --prefix "$prefix/node-tools" --save-exact "pnpm@$PNPM_VERSION"
    fi
    mkdir -p "$runtime_dir"
    # Harness itself pins only its top-level release. Use the tested dependency
    # graph too: newer Cordis releases can break rc.8 GUI startup.
    if [[ ! -e "$runtime_dir/package.json" && ! -e "$runtime_dir/pnpm-lock.yaml" ]]; then
        for file in package.json pnpm-lock.yaml; do
            [[ -f "$repo_dir/tools/harness-runtime/$file" ]] || die "Missing tools/harness-runtime/$file; run this script from a complete checkout."
            cp -- "$repo_dir/tools/harness-runtime/$file" "$runtime_dir/$file"
        done
    fi
    # pnpm 11 requires explicit approval of dependency build scripts. Permit the
    # known rc.8 native helpers, rather than enabling scripts for every package.
    if [[ ! -e "$runtime_dir/pnpm-workspace.yaml" ]]; then
        cp -- "$repo_dir/tools/harness-runtime/pnpm-workspace.yaml" "$runtime_dir/pnpm-workspace.yaml"
    fi
    touch "$runtime_dir/.genainet-install-pending"
    if [[ -f "$runtime_dir/pnpm-lock.yaml" ]]; then
        "$pnpm_bin" --dir "$runtime_dir" install --frozen-lockfile
        "$pnpm_bin" --dir "$runtime_dir" rebuild --pending
    else
        die "Existing runtime has no lockfile. Choose a fresh --runtime-dir to use the tested dependencies."
    fi
    rm -- "$runtime_dir/.genainet-install-pending"
fi
[[ -f "$package" && -f "$cli" ]] || die "Harness installation is incomplete: $runtime_dir"
installed_version=$("$node_bin" -e 'console.log(JSON.parse(require("fs").readFileSync(process.argv[1])).version)' "$package")
[[ "$installed_version" == "$HARNESS_VERSION" ]] || die "Found Harness $installed_version; expected $HARNESS_VERSION. Choose a new --runtime-dir."

export DSH_HOME="$config_dir"
export CHOKIDAR_USEPOLLING=1 CHOKIDAR_INTERVAL=1000
mkdir -p "$config_dir/workspace"
printf 'Initializing headless and GUI profiles…\n'
for profile in headless web; do
    (cd "$config_dir/workspace" && "$node_bin" "$cli" --profile "$profile" --dump-config >/dev/null)
done

# JSON quoting is valid YAML and safely handles paths and credential characters.
python3 - "$config_dir" "$repo_dir" <<'PY'
import json, pathlib, sys
home, repo = map(pathlib.Path, sys.argv[1:])
patch = home / 'cordis.patch.yml'
if not patch.exists():
    with patch.open('x') as stream:
        stream.write('''- id: llm-deepseek
  config:
    apiKeyEnv: DEEPSEEK_API_KEY
    baseURL: https://api.deepseek.com
    thinking: enabled
    reasoningEffort: high
    maxTokens: 256000
- id: agent-default-model
  config:
    provider: deepseek-official
    model: deepseek-v4-flash
''')
        wrapper = repo / 'tools/dsh_bwrap_resolved_tmp.sh'
        if wrapper.is_file():
            stream.write('- id: sandbox\n  config:\n    runnerCommand: ' + json.dumps([str(wrapper)]) + '\n    runnerFailureSignatures:\n      - "bwrap: "\n')
    print('Created default Flash v4 / high-reasoning configuration.')
else:
    print('Preserved existing Harness configuration.')
PY
if ((ask_key)) && [[ -t 0 && ! -e "$config_dir/.credentials.yaml" ]]; then
    python3 - "$config_dir" <<'PY'
import getpass, json, os, pathlib, sys
try:
    key = getpass.getpass('DeepSeek API key (Enter to set it later in the GUI): ').strip()
except (EOFError, KeyboardInterrupt):
    key = ''
if key:
    path = pathlib.Path(sys.argv[1]) / '.credentials.yaml'
    fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
    with os.fdopen(fd, 'w') as stream:
        stream.write('DEEPSEEK_API_KEY: ' + json.dumps(key) + '\n')
    print('Saved credential with owner-only permissions.')
else:
    print('API key skipped; configure it in the GUI provider settings.')
PY
else
    printf 'Existing credentials preserved; missing credentials can be set in the GUI.\n'
fi

python3 - "$prefix" "$config_dir" "$runtime_dir" "$node_bin" "$cli" "$repo_dir" "$port" "$open_browser" <<'PY'
import pathlib, shlex, sys
prefix, home, runtime, node, cli, repo, port, open_browser = sys.argv[1:]
q = shlex.quote
env = pathlib.Path(prefix) / 'env.sh'
with env.open('w') as stream:
    stream.write('# Generated by GenAI-Net install_harness.sh\n')
    for name, value in dict(GENAI_ROOT=repo, GENAI_DSH_HOME=home, DSH_HOME=home,
                            GENAI_DSH_RUNTIME=runtime, GENAI_DSH_CLI=cli,
                            RL4CRN_DSH_COMMAND=shlex.join([node, cli]),
                            CHOKIDAR_USEPOLLING='1', CHOKIDAR_INTERVAL='1000').items():
        stream.write(f'export {name}={q(value)}\n')
    path = str(pathlib.Path(node).parent) + ':' + prefix + '/node-tools/node_modules/.bin'
    stream.write(f'export PATH={q(path)}:"$PATH"\n')
launcher = pathlib.Path(prefix) / 'bin/harness-gui'
with launcher.open('w') as stream:
    stream.write('#!/usr/bin/env bash\n# Generated by GenAI-Net install_harness.sh\nset -euo pipefail\n')
    stream.write(f'source {q(str(env))}\ncd -- {q(home + "/workspace")}\n')
    command = [node, cli, '--profile', 'web', '--host', '127.0.0.1', '--port', port]
    if open_browser == '0':
        command.append('--no-open')
    stream.write('exec ' + shlex.join(command) + ' "$@"\n')
launcher.chmod(0o700)
PY
if ! command -v bwrap >/dev/null; then
    printf 'Note: install Bubblewrap before using sandboxed agent tools (Debian/Ubuntu: sudo apt-get install bubblewrap).\n'
fi
printf '\nHarness %s is ready.\nLoad the GenAI-Net environment:\n  source %q\nReopen the GUI:\n  %q\n' "$installed_version" "$prefix/env.sh" "$prefix/bin/harness-gui"
printf 'GUI address: http://127.0.0.1:%s\n' "$port"
if ((serve)); then
    printf 'Starting GUI in the foreground; Ctrl-C stops it.\n'
    cleanup
    scratch=""
    exec "$prefix/bin/harness-gui"
fi
